/** O rótulo do item que abre o relatório, para os menus de erro. */
export const itemDoRelatorio = (idioma: Idioma) => ({
  id: 'relatorio',
  rotulo: TEXTOS[idioma].item,
});

/** Só o nome do sistema, sem versão nem nada que identifique a máquina. */
function sistemaOperacional(): string {
  const agente = typeof navigator === 'undefined' ? '' : navigator.userAgent;
  if (/windows/i.test(agente)) return 'Windows';
  if (/mac os/i.test(agente)) return 'macOS';
  if (/linux/i.test(agente)) return 'Linux';
  return '?';
}

const NOME_DO_MESTRE: Record<IaDoMestre, string> = { claude_code: 'Claude Code', codex: 'Codex' };

/** O título e o corpo (Markdown) do relatório, já limpos. */
export function textoDoRelatorio(
  pedido: PedidoDeRelatorio,
  idioma: Idioma,
): { titulo: string; corpo: string } {
  const t = TEXTOS[idioma];
  const r = t.rotulos;
  const contexto: ContextoDoRelatorio = {
    repositorios: pedido.repositorios,
    nomes: pedido.nomes,
  };
  const d = detalhesDoErro(pedido.erro, contexto);
  const bloco = (texto: string) => ['```', texto, '```'].join('\n');
  const partes = [
    `### ${r.aconteceu}`,
    `**${r.onde}:** ${t.onde[pedido.onde]}`,
    `**${r.erro}:** ${d.tipo}${d.mensagem ? ` — ${d.mensagem}` : ''}`,
  ];
  if (d.problemas.length > 0)
    partes.push(`**${r.problemas}:**\n${d.problemas.map((p) => `- ${p}`).join('\n')}`);
  if (d.pilha) partes.push(`**${r.pilha}:**\n${bloco(d.pilha)}`);
  partes.push(
    `### ${r.ambiente}`,
    `Jogo ${version} · ${NOME_DO_MESTRE[pedido.mestre]} · ${sistemaOperacional()} · ${idioma}`,
    `---\n_${r.rodape}_`,
  );
  return { titulo: `[relatório] ${d.tipo}: ${t.onde[pedido.onde]}`, corpo: partes.join('\n\n') };
}

type Aviso = { tipo: 'ok' | 'erro'; texto: string } | null;

/** O Jogador lê e edita o relatório; só "Abrir no GitHub" faz algo sair, e pelo navegador dele. */
export function TelaDoRelatorio({
  pedido,
  onVoltar,
}: {
  pedido: PedidoDeRelatorio;
  onVoltar: () => void;
}) {
  const idioma = useIdioma();
  const t = TEXTOS[idioma];
  const [{ titulo, corpo: inicial }] = useState(() => textoDoRelatorio(pedido, idioma));
  const [corpo, setCorpo] = useState(inicial);
  const [aviso, setAviso] = useState<Aviso>(null);
  useEsc(onVoltar);

  function abrir() {
    if (!corpo.trim()) return setAviso({ tipo: 'erro', texto: t.vazio });
    abrirRelatorio(titulo, corpo).then(
      () => setAviso({ tipo: 'ok', texto: t.aberto }),
      (e: unknown) =>
        setAviso({
          tipo: 'erro',
          texto: formatar(t.falhou, {
            detalhe: typeof e === 'object' && e && 'codigo' in e ? String(e.codigo) : String(e),
          }),
        }),
    );
  }

  return (
    <main className="tela-relatorio">
      <Janela titulo={t.titulo} className="relatorio-janela">
        <p>{t.explica}</p>
        <p className="enviado-apagado">{t.github}</p>
        <label htmlFor="texto-do-relatorio">{t.rotulo}</label>
        <textarea
          id="texto-do-relatorio"
          className="relatorio-texto"
          value={corpo}
          spellCheck={false}
          onChange={(e) => setCorpo(e.target.value)}
        />
        {aviso && (
          <p
            role={aviso.tipo === 'erro' ? 'alert' : 'status'}
            className={aviso.tipo === 'erro' ? 'texto-erro' : 'texto-ok'}
          >
            {aviso.texto}
          </p>
        )}
        <Menu
          rotulo={t.titulo}
          itens={[
            { id: 'abrir', rotulo: t.abrir },
            { id: 'voltar', rotulo: t.voltar },
          ]}
          onEscolher={(id) => (id === 'abrir' ? abrir() : onVoltar())}
        />
      </Janela>
    </main>
  );
}
